#!/usr/bin/env node
// Assembles the convenience SQL files from the numbered sources in database/:
//   database/myenterprise_full.sql              00–06 (data, then pictures) in import order (non-destructive)
//   database/07_business_queries.sql            the seven queries in one file
//   database/reset/RESET_myenterprise_DESTRUCTIVE.sql   DROP + full rebuild
// Usage: node tools/build-sql.mjs   (npm run build:sql)

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DB = join(ROOT, 'database');
const read = (f) => readFileSync(join(DB, f), 'utf8').trimEnd() + '\n';

const parts = ['00_create_database.sql', '01_schema.sql', '02_functions.sql', '03_procedures.sql',
  '04_triggers.sql', '05_views.sql', '06_seed_data.sql', '06_seed_images.sql'];

const banner = (lines) => ['-- ' + '='.repeat(77), ...lines.map((l) => '-- ' + l), '-- ' + '='.repeat(77), ''].join('\n');

const full = banner([
  'MyEnterprise — complete database in one file (generated by tools/build-sql.mjs)',
  '',
  'phpMyAdmin: Import → choose this file → Go. Creates the `myenterprise`',
  'database, 31 tables, 6 functions, 6 procedures, 9 triggers, 3 views and the',
  'sample data, product pictures included (stored in ProductImage as binary).',
  'It does not drop anything: if the tables already exist the',
  'import stops at the first CREATE TABLE. To rebuild from scratch use',
  'database/reset/RESET_myenterprise_DESTRUCTIVE.sql instead.',
  '',
  'Sample sign-in for the shop and /admin: demo@gmail.com / password1234',
]) + parts.map((f) => `\n-- >>> ${f}\n` + read(f)).join('\n');
writeFileSync(join(DB, 'myenterprise_full.sql'), full);

mkdirSync(join(DB, 'reset'), { recursive: true });
const reset = banner([
  '⚠  DESTRUCTIVE — DELETES THE ENTIRE `myenterprise` DATABASE, THEN REBUILDS IT',
  '',
  'Every order, customer and change made through the shop or admin is lost and',
  'replaced by the original sample data. Only the `myenterprise` database is',
  'touched; other databases on the server are not. Use it to reset the demo',
  'before a presentation. (generated by tools/build-sql.mjs)',
]) + '\nDROP DATABASE IF EXISTS myenterprise;\n' + parts.map((f) => `\n-- >>> ${f}\n` + read(f)).join('\n');
writeFileSync(join(DB, 'reset', 'RESET_myenterprise_DESTRUCTIVE.sql'), reset);

const queries = readdirSync(join(DB, 'queries')).filter((f) => /^q\d_.*\.sql$/.test(f)).sort();
const combined = banner([
  'MyEnterprise — the seven business queries (generated by tools/build-sql.mjs)',
  '',
  'Each query sets its own parameters first (SET @date_from …); edit them and',
  'run one query at a time in the phpMyAdmin SQL tab. The PHP reports page runs',
  'the same SQL from database/queries/, with the dates you choose on screen.',
]) + '\nUSE myenterprise;\n' + queries.map((f) => `\n-- >>> queries/${f}\n` + read(join('queries', f)).replace('-- @query\n', '')).join('\n');
writeFileSync(join(DB, '07_business_queries.sql'), combined);

console.log(`built myenterprise_full.sql, reset/RESET_myenterprise_DESTRUCTIVE.sql, 07_business_queries.sql (${queries.length} queries)`);
